	"id"	INTEGER NOT NULL,
	"enterprise"	VARCHAR(45),
	"barcode"	VARCHAR(45),
	"name"	VARCHAR(45),
	"description"	VARCHAR(450),
	"designation"	VARCHAR(100),
	"index_list"	INTEGER,
	"list_count"	INTEGER,
	"parent_plan_id"	INTEGER,
	PRIMARY KEY("id"),
	FOREIGN KEY("parent_plan_id") REFERENCES "Plan"("id")
);
CREATE TABLE IF NOT EXISTS "Role" (
	"id"	INTEGER NOT NULL,
	"Name"	VARCHAR(45),
	"Description"	VARCHAR(450),
	"ParentRole_id"	INTEGER,
	PRIMARY KEY("id"),
	FOREIGN KEY("ParentRole_id") REFERENCES "Role"("id")
);
CREATE TABLE IF NOT EXISTS "Status" (
	"id"	INTEGER NOT NULL,
	"stype"	VARCHAR(100) NOT NULL,
	"description"	VARCHAR(255),
	"created_at"	DATETIME NOT NULL,
	PRIMARY KEY("id"),
	UNIQUE("stype")
);
CREATE TABLE IF NOT EXISTS "ToolTypes" (
	"id"	INTEGER NOT NULL,
	"name"	VARCHAR(45),
	"description"	VARCHAR(450),
	"count"	INTEGER,
	"img"	VARCHAR(45),
	"groups_id"	INTEGER,
	PRIMARY KEY("id"),
	FOREIGN KEY("groups_id") REFERENCES "Group"("id")
);
CREATE TABLE IF NOT EXISTS "Tools" (
	"id"	INTEGER NOT NULL,
	"inventory_number"	VARCHAR,
	"plan_id"	INTEGER,
	"tool_type_id"	INTEGER,
	PRIMARY KEY("id"),
	FOREIGN KEY("plan_id") REFERENCES "Plan"("id"),
	FOREIGN KEY("tool_type_id") REFERENCES "ToolTypes"("id")
);
CREATE TABLE IF NOT EXISTS "ToolsNorm" (
	"id"	INTEGER NOT NULL,
	"summa"	INTEGER,
	"summa_of_periods"	INTEGER,
	"description"	VARCHAR(450),
	"type_periods"	VARCHAR(45),
	"summa_of_use"	VARCHAR(45),
	"start_date"	DATETIME,
	"tools_id"	INTEGER NOT NULL,
	"actual_norm_id"	INTEGER NOT NULL,
	PRIMARY KEY("id"),
	FOREIGN KEY("actual_norm_id") REFERENCES "ActualNorm"("id"),
	FOREIGN KEY("tools_id") REFERENCES "Tools"("id")
